#!/usr/bin/env python3
"""Sine table and three cyclic colour gradients (RGB332, as the module's palette entries) -> paltab.h"""
import math, colorsys
def q332(r, g, b): return (round(r * 7) << 5) | (round(g * 7) << 2) | round(b * 3)
def hue(t):  return colorsys.hsv_to_rgb(t % 1, 1.0, 1.0)
def ice(t):
    k = 0.5 - 0.5 * math.cos(2 * math.pi * t); return (k * k * 0.9, 0.15 + 0.85 * k, 0.45 + 0.55 * k)
def fire(t):
    k = 0.5 - 0.5 * math.cos(2 * math.pi * t); return (min(1, 0.25 + 1.5 * k), k ** 1.6, 0.35 * (1 - k) + 0.09 * max(0, k - 0.8) * 5)
def arr(name, data):
    s = f"static const uint8_t __code {name}[{len(data)}] = {{\n"
    for i in range(0, len(data), 16): s += "    " + ",".join(f"0x{v:02X}" for v in data[i:i + 16]) + ",\n"
    return s + "};\n"
h = "/* generated by gen_paltab.py - do not edit */\n#ifndef PALTAB_H\n#define PALTAB_H\n\n"
h += arr("sin8", [min(255, int(math.sin(i * 2 * math.pi / 256) * 127 + 128)) for i in range(256)])
for n, g in (("grad_hue", hue), ("grad_ice", ice), ("grad_fire", fire)): h += arr(n, [q332(*g(i / 256)) for i in range(256)])
h += "\n#endif\n"
open('paltab.h', 'w').write(h)

ORDER = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ:.-+>"
def rows(art): return [l for l in art.strip('\n').split('\n')]
def pack(art, width):
    out = []
    for l in rows(art):
        assert len(l) == width, (len(l), l)
        for b in range(0, width, 8): out.append(int(l[b:b + 8].replace('#', '1').replace('.', '0'), 2))
    return out
def arr(name, data, per):
    s = f"static const uint8_t __code {name}[{len(data)}] = {{\n"
    for i in range(0, len(data), per): s += "    " + ", ".join(f"0x{v:02X}" for v in data[i:i + per]) + ",\n"
    return s + "};\n"

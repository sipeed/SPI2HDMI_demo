#!/usr/bin/env python3
"""roms/manifest.txt + roms/*.ch8 -> roms.h.  Usage: gen_roms.py [max_total_bytes]"""
import sys
QB = {'shiftQuirks': 1, 'loadStoreQuirks': 2, 'clipQuirks': 4, 'vBlankQuirks': 8, 'logicQuirks': 16}
limit = int(sys.argv[1]) if len(sys.argv) > 1 else 1 << 30
ent, total = [], 0
for l in open('roms/manifest.txt'):
    l = l.strip()
    if not l or l[0] == '#': continue
    f, name, rate, q = [x.strip() for x in l.split('|')]
    data = open('roms/' + f, 'rb').read()
    bad = [x for x in q.split(',') if x and x not in QB]
    if bad: sys.exit(f'{f}: unsupported quirk {bad}')
    if len(data) > 3584 or total + len(data) > limit: continue
    total += len(data)
    ent.append((f, name, min(int(rate), 60), sum(QB[x] for x in q.split(',') if x), data))
h = "/* generated by gen_roms.py - do not edit */\n#ifndef ROMS_H\n#define ROMS_H\n\n"
for i, (f, name, rate, q, data) in enumerate(ent):
    h += f"static const uint8_t __code rom{i}[{len(data)}] = {{ /* {f} */\n"
    for k in range(0, len(data), 16): h += "    " + ",".join(f"0x{b:02X}" for b in data[k:k + 16]) + ",\n"
    h += "};\n"
h += "\ntypedef struct { const char *name; const uint8_t __code *data; uint16_t size; uint8_t rate, quirks; } rom_t;\n"
h += f"#define NROMS {len(ent)}\nstatic const rom_t __code roms[NROMS] = {{\n"
for i, (f, name, rate, q, data) in enumerate(ent): h += f'    {{ "{name}", rom{i}, {len(data)}, {rate}, {q} }},\n'
h += "};\n\n#endif\n"
open('roms.h', 'w').write(h)
print(f'{len(ent)} programs, {total} bytes')
